/**
 * The remembered language, or Vietnamese.
 *
 * Wrapped because this runs at *import* time, before any component mounts, so a throw here takes
 * the whole app down rather than degrading one feature — and reading `localStorage` genuinely
 * throws in a browser configured to block site data, which `lib/reviewer.ts` already defends
 * against for the same reason. A visitor whose storage is locked down gets the default language
 * instead of a blank page.
 */
function savedLanguage(): string {
  try {
    return localStorage.getItem('ssp_lang') || 'vi';
  } catch {
    return 'vi';
  }
}

